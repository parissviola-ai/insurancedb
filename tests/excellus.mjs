import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pdfMatches} from '../docs/healthspring-providers.js';
import {excellusSuggestions} from '../docs/excellus-providers.js';
const data=JSON.parse(fs.readFileSync(new URL('../docs/data/excellus.json',import.meta.url)));
const dir=JSON.parse(fs.readFileSync(new URL('../docs/data/excellus-providers.json',import.meta.url)));
assert.equal(data.plans.length,3);
assert.deepEqual(data.plans.map(p=>p.cms_id),['H3351-028-000','H3351-029-000','H3351-030-000']);
assert.deepEqual(data.plans.map(p=>p.benefit_metrics.premium.amount),[14,85.3,125.3]);
assert.deepEqual(data.plans.map(p=>p.benefit_metrics.vision.amount),[0,200,200]);
assert(data.plans.every(p=>p.counties.length===13&&!p.benefit_metrics.otc&&!p.benefit_metrics.dental&&p.benefit_metrics.transportation.amount===0));
const rows=Object.values(data.formularies)[0].rows;
assert.equal(rows.find(r=>r.name==='atorvastatin').tier,'1');
assert.equal(rows.find(r=>r.name==='amlodipine-atorvastatin').tier,'2');
assert.match(rows.find(r=>r.name==='amlodipine-atorvastatin').restrictions,/QL/);
assert(dir.rows.every(r=>!r.name.includes('Gender:')&&r.phone&&r.page>0));
globalThis.fetch=async()=>({ok:true,json:async()=>dir});
const found=await excellusSuggestions('Bridgewater Center','facility','NY');assert(found.options.length);
const selection=found.options[0];assert.equal(selection.directory_date,'2026-09-13');
assert.equal(pdfMatches(selection,data.plans).get(data.plans[0].id).length,1);
for(const plan of [{...data.plans[0],year:2026},{...data.plans[0],state:'NC'},{...data.plans[0],cms_id:'H3351-031-000'}])assert.equal(pdfMatches(selection,[plan]).get(plan.id).length,0);
assert.equal((await excellusSuggestions('Bridgewater Center','facility','NC')).options.length,0);
assert.equal((await excellusSuggestions('1234567890','provider','NY')).options.length,0);
assert((await excellusSuggestions('Bishop Kristen','provider','NY')).options.length);
console.log('Excellus: CMS scope, benefits, standalone/combination drugs, restrictions, provider/facility names and PDF year/state/segment isolation passed.');
