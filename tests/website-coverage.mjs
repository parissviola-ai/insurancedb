import assert from 'node:assert/strict';
import fs from 'node:fs';
import {officialId,preparedPlan,medicationChecks,evaluateWebsiteCoverage} from '../docs/website-coverage.js';
const inventory=JSON.parse(fs.readFileSync(new URL('../docs/data/plans.json',import.meta.url)));
const formularies=JSON.parse(fs.readFileSync(new URL('../docs/data/formularies.json',import.meta.url)));
const prepared=inventory.plans.find(p=>p.state==='NC'&&!p.ma_only&&p.documents.some(d=>d.kind==='formulary'));
const publicPlan={id:'public-fixture',carrier:prepared.carrier,official_id:officialId(prepared),year:2027,state:'NC',business:'Medicare Advantage'};
assert.equal(preparedPlan(publicPlan,inventory).id,prepared.id);
assert.equal(preparedPlan({...publicPlan,year:2026},inventory),null);
assert.equal(preparedPlan({...publicPlan,state:'PA'},inventory),null);
assert.equal(preparedPlan({...publicPlan,carrier:'Aetna'},inventory),null);
assert.equal(preparedPlan({...publicPlan,official_id:publicPlan.official_id.slice(0,9)},inventory),null);
const item={name:'atorvastatin',manual:true,label:'atorvastatin 20 mg tablet (manual)'};
const checks=medicationChecks(publicPlan,prepared,[item],formularies);
assert.equal(checks[0].status,'review_required');assert(checks[0].matches.length);
assert(checks[0].matches.every(m=>m.source_url.includes('#page=')));
assert.equal(medicationChecks(publicPlan,null,[item],formularies)[0].status,'not_connected');
assert.equal(medicationChecks({...publicPlan,has_drug_coverage:false},null,[item],formularies)[0].matches.length,0);
assert.match(medicationChecks(publicPlan,prepared,[{name:'fixture-no-such-drug',manual:true}],formularies)[0].message,/does not establish exclusion/);
const unknown={...publicPlan,id:'unconnected',carrier:'Aetna'};
let requests=0;const original=globalThis.fetch;globalThis.fetch=async()=>{requests++;throw Error('No unexpected remote requests');};
const context={medications:[item],providers:[{manual:true,term:'Fixture doctor',kind:'provider'}],loadData:async()=>[inventory,{},formularies]};
const result=await evaluateWebsiteCoverage([unknown],context,new AbortController().signal);
assert.equal(result.get('unconnected').providers[0].status,'not_connected');assert.equal(requests,0);
const pdp=await evaluateWebsiteCoverage([{...unknown,business:'Part D'}],context,new AbortController().signal);
assert.equal(pdp.get('unconnected').providers[0].status,'not_applicable');
globalThis.fetch=original;
console.log('Website coverage passed: exact carrier/segment/state/year joins, source pages, medical-only/PDP handling and explicit unconnected checks.');
// Reuse the all-state HealthSpring library for a segment outside the NC pilot.
const library=JSON.parse(fs.readFileSync(new URL('../docs/data/healthspring-formularies.json',import.meta.url)));
const [key,mapping]=Object.entries(library.plan_links).find(([k,v])=>k.startsWith('AL:')&&v.urls.length);
const [state,id]=key.split(':');const source=library.documents[mapping.urls[0]];
const drug=source.rows[0].name;
globalThis.fetch=async()=>({ok:true,json:async()=>library});
const hs={id:'hs-library',official_id:id,carrier:'HealthSpring',year:2027,state,business:'Medicare Advantage'};
const hsResult=await evaluateWebsiteCoverage([hs],{medications:[{name:drug,manual:false}],providers:[],loadData:async()=>[{plans:[]},{},{}]},new AbortController().signal);
assert.equal(hsResult.get(hs.id).medications[0].status,'review_required');
assert(hsResult.get(hs.id).medications[0].matches[0].source_date);
globalThis.fetch=original;
console.log('HealthSpring all-state exact-segment formulary reuse passed.');
